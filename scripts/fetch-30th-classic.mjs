// fetch-30th-classic.mjs — build data/cards-30th-c.js: "30th Classic Collection"
// (TCGplayer: "ME: 30th Celebration Classic Collection", group 24837), the 30 classic
// reprints released with 30th Celebration on 2026-09-16.
//
// TCGdex catalogues it as "30th-c" (order, illustrator, types) but has NO images
// or prices for it, so art is the TCGplayer product image (fullImg, ~660x920) and
// prices are TCGplayer market via TCGCSV. TCGdex numbers the 30 cards in order of
// their ORIGINAL card number, which is how the TCGCSV rows are paired with them
// (sorted by original number, then product id); every pair is name-checked.
// Run: node scripts/fetch-30th-classic.mjs     (Node >= 18, no deps)
'use strict';
import { writeFileSync, renameSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SET_ID = '30th-c', GROUP = 24837;
const UA = { headers: { 'User-Agent': 'CrownsTCG/1.0 (personal card tracker)' } };
async function getJson(url, tries = 4) {
  for (let t = 1; ; t++) {
    try { const r = await fetch(url, UA); if (!r.ok) throw new Error(`HTTP ${r.status} ${url}`); return await r.json(); }
    catch (e) { if (t >= tries) throw e; await new Promise((s) => setTimeout(s, 500 * t)); }
  }
}
const ext = (p, k) => (p.extendedData || []).find((e) => e.name === k)?.value ?? null;
const first = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9 ]+/g, ' ').trim().split(/\s+/)[0];

const base = `https://tcgcsv.com/tcgplayer/3/${GROUP}`;
const [prod, price, set] = await Promise.all([
  getJson(`${base}/products`), getJson(`${base}/prices`), getJson(`https://api.tcgdex.net/v2/en/sets/${SET_ID}`),
]);
let tcgUpdated = null;
try { tcgUpdated = (await (await fetch('https://tcgcsv.com/last-updated.txt', UA)).text()).trim() || null; } catch {}
const best = {};
for (const r of price.results || []) {
  const v = r.marketPrice ?? r.midPrice;
  if (typeof v === 'number' && (!best[r.productId] || v > best[r.productId].v)) best[r.productId] = { v, r };
}
const rows = (prod.results || []).filter((p) => ext(p, 'Number'))
  .map((p) => ({ p, num: ext(p, 'Number'), n: parseInt(ext(p, 'Number'), 10) }))
  .sort((a, b) => a.n - b.n || a.p.productId - b.p.productId);
const stubs = [...(set.cards || [])].sort((a, b) => parseInt(a.localId, 10) - parseInt(b.localId, 10));
if (rows.length !== stubs.length) throw new Error(`TCGCSV ${rows.length} cards vs TCGdex ${stubs.length} — pairing unsafe`);
const details = await Promise.all(stubs.map((s) => getJson(`https://api.tcgdex.net/v2/en/cards/${s.id}`).catch(() => s)));

const cards = rows.map(({ p, num }, i) => {
  const d = details[i];
  if (first(d.name) !== first(p.name)) throw new Error(`pairing mismatch at ${d.localId}: "${d.name}" vs "${p.name}"`);
  const b = best[p.productId];
  return {
    id: d.id, localId: d.localId, num: parseInt(d.localId, 10),
    name: p.name.replace(/\s+-\s+.*$/, '').trim(), rarity: ext(p, 'Rarity') || 'Classic Collection',
    category: d.category || 'Pokemon', illustrator: d.illustrator ?? null, types: d.types ?? [],
    image: `https://tcgplayer-cdn.tcgplayer.com/product/${p.productId}_in_1000x1000.jpg`, fullImg: true,
    priceUsd: b ? +b.v.toFixed(2) : null, priceVariant: b ? 'holofoil' : null,
    variants: b ? { holofoil: { low: b.r.lowPrice ?? null, mid: b.r.midPrice ?? null, market: b.r.marketPrice ?? null } } : {},
    cardmarket: null, tcgplayerUpdated: b ? tcgUpdated : null, imageOk: true,
    meta: [['Set', '30th Classic Collection'], ['Original number', String(num)]],
  };
});

const payload = {
  set: { id: SET_ID, name: set.name || '30th Classic Collection', total: cards.length, official: cards.length, logo: '' },
  snapshotAt: new Date().toISOString(),
  source: `TCGplayer via TCGCSV group ${GROUP} (art + USD market) · TCGdex (illustrator/types)`,
  cards,
};
const out = join(ROOT, 'data', `cards-${SET_ID}.js`), tmp = out + '.tmp';
writeFileSync(tmp,
  `// 30th Classic Collection — GENERATED by scripts/fetch-30th-classic.mjs (TCGCSV group ${GROUP}\n`
  + `// art + prices, TCGdex "30th-c" metadata). Re-run any time to refresh.\n`
  + `window.CARD_SETS = window.CARD_SETS || {};\n`
  + `window.CARD_SETS[${JSON.stringify(SET_ID)}] = ${JSON.stringify(payload)};\n`);
for (let i = 0; ; i++) { try { renameSync(tmp, out); break; } catch (e) { if (i >= 5) throw e; await new Promise((s) => setTimeout(s, 300 * (i + 1))); } }
console.log(`wrote data/cards-${SET_ID}.js — ${cards.length} cards, ${cards.filter((c) => c.priceUsd != null).length} priced`);
