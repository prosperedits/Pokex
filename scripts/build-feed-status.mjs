// build-feed-status.mjs: write data/feed-status.js for the Live data page, so the page
// can say honestly how fresh each source is (Faisal, 27 Oct: "I don't know if the live
// feed's still working"). Reads the last refresh report, the price index, the bundled
// sets and the price history; no network.
// Run: node scripts/build-feed-status.mjs   (last step of refresh-all.mjs)
'use strict';

import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DATA = join(ROOT, 'data');
const load = (f, win = {}) => { new Function('window', readFileSync(join(DATA, f), 'utf8'))(win); return win; };

// price index: cards and priced cards per game, and when the file was written
const idx = {};
for (const f of readdirSync(DATA)) if (/^card-index.*\.js$/.test(f)) load(f, idx);
const rows = Object.values(idx).filter(Array.isArray).flat();
const games = {};
for (const c of rows) {
  const g = games[c.g] || (games[c.g] = { cards: 0, priced: 0, sets: new Set() });
  g.cards++; if (typeof c.p === 'number') g.priced++; g.sets.add(c.s);
}
for (const g of Object.values(games)) g.sets = g.sets.size;
const indexAt = statSync(join(DATA, 'card-index.js')).mtime.toISOString();

// bundled Pokémon sets (TCGdex art + TCGplayer/Cardmarket prices)
const sets = load_sets();
function load_sets() {
  const w = { CARD_SETS: {} };
  for (const f of readdirSync(DATA)) if (/^cards-.*\.js$/.test(f)) { try { load(f, w); } catch { /* skip a bad file */ } }
  return w.CARD_SETS;
}
let pkCards = 0, pkPriced = 0, latestSnap = null;
for (const s of Object.values(sets)) {
  for (const c of s.cards || []) { pkCards++; if (typeof c.priceUsd === 'number') pkPriced++; }
  if (s.snapshotAt && (!latestSnap || s.snapshotAt > latestSnap)) latestSnap = s.snapshotAt;
}

// the refresh run itself
const rep = existsSync(join(DATA, 'refresh-all-report.json')) ? JSON.parse(readFileSync(join(DATA, 'refresh-all-report.json'), 'utf8')) : null;
const steps = rep ? rep.steps.map((s) => ({ step: s.step, ok: s.ok, secs: s.secs })) : [];
const histDir = join(ROOT, 'price-history');
const days = existsSync(histDir) ? readdirSync(histDir).filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort() : [];

const sources = [
  { name: 'TCGplayer market prices', via: 'TCGCSV (tcgcsv.com)', games: ['pokemon', 'magic', 'lorcana', 'onepiece'], what: 'Market price of every card and sealed product', at: indexAt, ok: !steps.length || steps.find((s) => /card index/.test(s.step))?.ok !== false },
  { name: 'TCGdex', via: 'api.tcgdex.net', games: ['pokemon'], what: 'Pokémon card art, rarities and Cardmarket averages (1, 7 and 30 days)', at: latestSnap, ok: steps.filter((s) => /^set /.test(s.step)).every((s) => s.ok) },
  { name: 'Scryfall', via: 'api.scryfall.com', games: ['magic'], what: 'Magic cards and prices, fetched live when you open a set', at: null, live: true, ok: true },
  { name: 'Lorcast', via: 'api.lorcast.com', games: ['lorcana'], what: 'Lorcana cards and prices, fetched live when you open a set', at: null, live: true, ok: true },
  { name: 'dotGG', via: 'static.dotgg.gg', games: ['onepiece'], what: 'One Piece card art and prices', at: existsSync(join(DATA, 'onepiece.js')) ? statSync(join(DATA, 'onepiece.js')).mtime.toISOString() : null, ok: steps.find((s) => /One Piece/.test(s.step))?.ok !== false },
];

const payload = {
  generatedAt: new Date().toISOString(),
  refresh: rep ? { startedAt: rep.startedAt, finishedAt: rep.finishedAt, steps: steps.length, failed: (rep.failed || []).length } : null,
  games, pokemonBundled: { cards: pkCards, priced: pkPriced, sets: Object.keys(sets).length },
  historyDays: days.length, firstDay: days[0] || null,
  sources,
};
writeFileSync(join(DATA, 'feed-status.js'),
  `// AUTO-GENERATED by scripts/build-feed-status.mjs: freshness of every data source, for data.html.\n`
  + `window.FEED_STATUS = ${JSON.stringify(payload)};\n`);
console.log(`feed status: ${rows.length} indexed cards; games ${Object.entries(games).map(([g, v]) => `${g} ${v.cards}/${v.priced} priced`).join(', ')}; history ${days.length} day(s)`);
