// snapshot-prices.mjs — keep a daily price history for every game, so trends exist
// beyond Pokémon (only Pokémon has Cardmarket averages; Magic, Lorcana and One Piece
// prices from TCGCSV are today's number only).
//
// Each run writes price-history/<YYYY-MM-DD>.json ({ cardId: usd } for cards >= $3,
// gitignored, local to the PC that runs the refresh) and rebuilds data/trends.js
// (committed): { cardId: [pct7, pct30] } from the oldest snapshots 7 and 30 days back.
// Run: node scripts/snapshot-prices.mjs   (also step of refresh-all.mjs)
'use strict';

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DATA = join(ROOT, 'data');
const HIST = join(ROOT, 'price-history');
const MIN_USD = 3;
mkdirSync(HIST, { recursive: true });

// every card-index*.js assigns one array onto window; collect them all
const win = {};
for (const f of readdirSync(DATA)) {
  if (!/^card-index.*\.js$/.test(f)) continue;
  new Function('window', readFileSync(join(DATA, f), 'utf8'))(win);
}
const today = {};
for (const v of Object.values(win)) {
  if (!Array.isArray(v)) continue;
  for (const c of v) if (c && c.i != null && typeof c.p === 'number' && c.p >= MIN_USD) today[c.i] = c.p;
}
const day = new Date().toISOString().slice(0, 10);
writeFileSync(join(HIST, `${day}.json`), JSON.stringify(today));

// trend vs the snapshot closest to N days ago (only once that much history exists)
const days = readdirSync(HIST).filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort();
const ago = (n) => {
  const want = new Date(Date.now() - n * 864e5).toISOString().slice(0, 10);
  const older = days.filter((d) => d.slice(0, 10) <= want);
  return older.length ? JSON.parse(readFileSync(join(HIST, older[older.length - 1]), 'utf8')) : null;
};
const w1 = ago(7), m1 = ago(30);
const trends = {};
let n = 0;
for (const [id, p] of Object.entries(today)) {
  const a = w1 && w1[id], b = m1 && m1[id];
  if (!a && !b) continue;
  trends[id] = [a ? +((p - a) / a * 100).toFixed(1) : null, b ? +((p - b) / b * 100).toFixed(1) : null];
  n++;
}
writeFileSync(join(DATA, 'trends.js'),
  `// AUTO-GENERATED by scripts/snapshot-prices.mjs: [7-day %, 30-day %] per card id, from daily snapshots.\n`
  + `window.PRICE_TRENDS = ${JSON.stringify({ generatedAt: new Date().toISOString(), days: days.length, trends })};\n`);
console.log(`snapshot ${day}: ${Object.keys(today).length} cards >= $${MIN_USD}; ${days.length} day(s) of history; trends for ${n} cards`);
